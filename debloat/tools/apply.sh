#!/bin/sh
# apply.sh - disable every app_id in a debloat list on the TV.  TV-side
# busybox sh; runs as root (the caller pipes it over the root channel).
#
#   APPLY=0 sh apply.sh lists/batch1-tracking.txt   # dry run: print only
#   sh apply.sh lists/batch1-tracking.txt           # real run
#   tools/restore.sh lists/batch1-tracking.txt      # undo (same list)
#
# Discipline (adopted from cleanyourtv, hardened here):
#   * the list is one app_id per line, '#'-comments allowed;
#   * every line is validated as a bare id BEFORE it reaches a command;
#   * a hard denylist (Smart Hub dependency, privacy-choice UIs, our own
#     carrier, Vetro itself) is refused even if the list asks;
#   * the undo line is recorded BEFORE each disable;
#   * disable only - never uninstall.
#
# --global is the persistent switch: it writes
# package_app_info.app_disable in /opt/dbspace/.pkgmgr_parser.db.
# --uid only flips in-memory activation (pkgcmd --help) and the row stays
# 'false', which is why a mains cycle brought the apps back. A second
# --global on an app that is already disabled exits 25 ("Failed to get
# appinfo") and leaves the row true, so the sqlite flag is the result,
# not pkgcmd's exit code.
set -u

LIST="${1:-}"
[ -n "$LIST" ] && [ ! -f "$LIST" ] && { echo "list not found: $LIST"; exit 2; }

APPLY="${APPLY:-1}"
UNDO_LOG="${UNDO_LOG:-/opt/usr/home/owner/share/debloat-undo-$(date +%Y%m%d-%H%M%S).sh}"
OWNER_HOME=/opt/usr/home/owner
SHARE="$OWNER_HOME/share"
DB=/opt/dbspace/.pkgmgr_parser.db

# never disable these, whatever the list says
DENY="com.samsung.tv.coba.adagent com.samsung.tv.coba.privacy_app tv6pbVMQFF
com.samsung.tv.MultiControl-Service vetrotvapp"


mkdir -p "$SHARE" 2>/dev/null
if [ "$APPLY" = "1" ]; then
  { echo '#!/bin/sh'; echo '# undo log - generated by apply.sh'; } > "$UNDO_LOG"
  echo "undo log: $UNDO_LOG"
fi

ok=0; fail=0; dry=0; denied=0; n=0
while IFS= read -r line || [ -n "$line" ]; do
  case "$line" in ''|\#*) continue ;; esac
  id=$(printf '%s' "$line" | tr -d '\r' | awk '{$1=$1};1')
  [ -n "$id" ] || continue   # whitespace-only line
  case "$id" in *' '*|*';'*|*'&'*|*'|'*|*'`'*|*'$'*) echo "REFUSE (not a bare id): $id"; fail=$((fail+1)); continue ;; esac
  case "$id" in
    *[!A-Za-z0-9@._-]*) echo "REFUSE (not a bare id): $id"; fail=$((fail+1)); continue ;;
  esac
  denied=0
  for d in $DENY; do [ "$id" = "$d" ] && denied=1; done
case "$id" in vetrotvapp*) denied=1 ;; esac
  if [ "$denied" = "1" ]; then echo "REFUSE (denylist): $id"; fail=$((fail+1)); continue; fi

  n=$((n+1))
  if [ "$APPLY" != "1" ]; then
    echo "DRY[$n] pkgcmd -D -t app -n '$id' --global"
    dry=$((dry+1))
    continue
  fi
  { echo "echo undo: pkgcmd -A -t app -n '$id' --global"; echo "pkgcmd -A -t app -n '$id' --global"; } >> "$UNDO_LOG"
  pkgcmd -D -t app -n "$id" --global >/tmp/pkgcmd-apply.out 2>&1
  flag=$(sqlite3 "$DB" "select app_disable from package_app_info where app_id='$id';")
  if [ "$flag" = "true" ]; then
    echo "disabled[$n]: $id"
    ok=$((ok+1))
  else
    echo "FAILED[$n]: $id flag=${flag:-missing} (undo line already recorded; stopping per discipline #2)"
    tail -2 /tmp/pkgcmd-apply.out
    exit 1
  fi
done < "${LIST:--}"

# ---- finalize: avocd new_home flag (picture-settings grey-out guard) ----
# Disabling apps / stopping their services can race Samsung Home's flag
# reset and leave motion processing forced off.  Resetting it is what Home
# itself does when it hides - safe, memory-only.  Fail-open: a missing
# dbus-send or a failed call only prints a hint.
# See debloat/models/qnx1d/run-2026-10-29-services-bind.md round 5.
if [ "$APPLY" = "1" ] && [ "${AVOCD:-1}" = "1" ] && command -v dbus-send >/dev/null 2>&1; then
  if dbus-send --system --print-reply --dest=org.tizen.tv.avoc /org/tizen/tv/avoc \
      org.tizen.tv.avoc.AvOutputControl.SetNewHome int32:0 >/dev/null 2>&1; then
    st=$(dbus-send --system --print-reply --dest=org.tizen.tv.avoc /org/tizen/tv/avoc \
      org.tizen.tv.avoc.AvOutputControl.CheckAutoMotionPlus 2>/dev/null \
      | awk '/int32/{print $NF}')
    echo "picture-guard: new_home=0 (CheckAutoMotionPlus=${st:-?}; 1 = picture settings available)"
    [ "$st" = "1" ] || echo "picture-guard: WARNING - still forced off; rerun SetNewHome or use the 30 s loop (tcc ch. 6)"
  else
    echo "picture-guard: dbus call failed - skipped (run the SetNewHome command manually)"
  fi
fi

if [ "$APPLY" = "1" ]; then
  echo
  echo "summary: disabled=$ok failed=$fail of $n (undo: sh $UNDO_LOG)"
  [ "$fail" = "0" ] || exit 1
else
  echo
  echo "dry run: would disable $dry of $n entries (re-run with APPLY=1)"
fi
