#!/bin/sh
# apply.sh - disable every app_id in a debloat list on the TV.  TV-side
# busybox sh; runs as root (the caller pipes it over the root channel).
#
#   APPLY=0 sh apply.sh lists/batch1-tracking.txt   # dry run: print + gate
#   sh apply.sh lists/batch1-tracking.txt           # real run
#   tools/restore.sh lists/batch1-tracking.txt      # undo (same list)
#
# The list MUST be a file argument (a path on the TV).  There is no stdin
# fallback: the usual invocation is `cat apply.sh | sh -s <list>`, so stdin
# already carries the script - reading a list from it would consume the
# script.  (Review 2026-10-30: the old `${LIST:--}` default expanded to a
# literal file named "-", so the no-arg run printed "0 of 0" and exited 0.)
#
# Discipline (adopted from cleanyourtv, hardened here):
#   * the list is one app_id per line, '#'-comments allowed;
#   * every line is validated as a bare id BEFORE it reaches a command;
#   * a hard denylist (Smart Hub dependency, privacy-choice UIs, our own
#     carrier, Home/menu, DRM, screen-analysis, Vetro itself) is refused
#     even if the list asks;
#   * the undo line is recorded BEFORE each disable;
#   * disable only - never uninstall;
#   * a dry run exits non-zero on a refusal, so APPLY=0 gates the real run;
#   * an empty or fully-refused list exits 2 instead of "success, 0 done".
#
# --global is the persistent switch: it writes
# package_app_info.app_disable in /opt/dbspace/.pkgmgr_parser.db.
# --uid only flips in-memory activation (pkgcmd --help) and the row stays
# 'false', which is why a mains cycle brought the apps back. A second
# --global on an app that is already disabled exits 25 ("Failed to get
# appinfo") and leaves the row true, so the sqlite flag is the result,
# not pkgcmd's exit code.
#
# canalysis/pisa systemd units ignore app_disable (Restart=always). The
# durable off-switch is an empty sentinel under
# /opt/usr/share/systemd/system (vendor ConditionPathExists=!). apply.sh
# plants those when the matching package is disabled; restore.sh removes
# them. Undo logs live in /opt/usr/data (root-owned) and must be replayed
# as `cat file | sh` — UEP blocks `sh /path/to/file`.
set -u

LIST="${1:-}"
[ -n "$LIST" ] || { echo "usage: apply.sh <list-file>  (the list must be a file; stdin carries the script when piped)"; exit 2; }
[ -f "$LIST" ] || { echo "list not found: $LIST"; exit 2; }

APPLY="${APPLY:-1}"
UNDO_LOG="${UNDO_LOG:-/opt/usr/data/debloat-undo-$(date +%Y%m%d-%H%M%S).sh}"
DATA=/opt/usr/data
SENTINEL_DIR=/opt/usr/share/systemd/system
DB=/opt/dbspace/.pkgmgr_parser.db

# never disable these, whatever the list says
# screen-analysis-dbmgr is not role=tracking any more (see the tier-1 header):
# tcc measured picture-processing breakage when it is blocked, so it is a
# denylist entry rather than a comment a future list can ignore.
DENY="com.samsung.tv.coba.adagent com.samsung.tv.coba.privacy_app tv6pbVMQFF
com.samsung.tv.MultiControl-Service org.tizen.menu com.samsung.tv.home.sidebar
com.samsung.tv.screen-analysis-dbmgr vetrotvapp"


mkdir -p "$DATA" "$SENTINEL_DIR" 2>/dev/null
if [ "$APPLY" = "1" ]; then
  { echo '#!/bin/sh'; echo '# undo log - generated by apply.sh'; echo '# replay: cat this file | sh  (UEP blocks sh /path/file)'; } > "$UNDO_LOG"
  echo "undo log: $UNDO_LOG"
  echo "replay: cat $UNDO_LOG | sh"
fi

picture_guard() {
  # Disabling apps / stopping their services can race Samsung Home's flag
  # reset and leave motion processing forced off.  Run even on a failed
  # apply — a partial batch is enough to grey out Picture Mode.
  # See debloat/models/qnx1d/run-2026-10-29-services-bind.md round 5.
  # ONE-SHOT only: the persistent 30 s loop lives in tools/mask.sh
  # (`newhome-fix`), which owns the service session this race comes from.
  [ "$APPLY" = "1" ] && [ "${AVOCD:-1}" = "1" ] && command -v dbus-send >/dev/null 2>&1 || return 0
  if dbus-send --system --print-reply --dest=org.tizen.tv.avoc /org/tizen/tv/avoc \
      org.tizen.tv.avoc.AvOutputControl.SetNewHome int32:0 >/dev/null 2>&1; then
    st=$(dbus-send --system --print-reply --dest=org.tizen.tv.avoc /org/tizen/tv/avoc \
      org.tizen.tv.avoc.AvOutputControl.CheckAutoMotionPlus 2>/dev/null \
      | awk '/int32/{print $NF}')
    # 1 = settings available now.  0 is NOT a failure by itself: while Samsung
    # Home is in front, Home keeps motion processing off, so the readback is 0
    # regardless of the flag we just cleared.  Only an empty answer is a fault.
    echo "picture-guard: new_home=0 (CheckAutoMotionPlus=${st:-?}; 1 = settings available, 0 while Samsung Home is in front)"
    [ -n "$st" ] || echo "picture-guard: WARNING - the verify call returned nothing"
  else
    echo "picture-guard: dbus call failed - skipped (run the SetNewHome command manually)"
  fi
}

read_flag() {
  sqlite3 "$DB" ".timeout 5000" "select app_disable from package_app_info where app_id='$1';"
}

# Vendor ConditionPathExists=! sentinels. pisa-service also blocks adagent-service.
plant_sentinel() {
  id="$1"
  sent=; units=
  case "$id" in
    com.samsung.tv.canalysis-service) sent=canalysis-daemon; units="canalysis-service.service" ;;
    com.samsung.tv.pisa-service) sent=pisa-service; units="pisa-service.service adagent-service.service" ;;
    *) return 0 ;;
  esac
  if [ "$APPLY" != "1" ]; then
    echo "DRY sentinel $SENTINEL_DIR/$sent (stop $units)"
    return 0
  fi
  { echo "echo undo: rm -f $SENTINEL_DIR/$sent"; echo "rm -f $SENTINEL_DIR/$sent"; } >> "$UNDO_LOG"
  if : > "$SENTINEL_DIR/$sent"; then
    echo "sentinel: $sent"
  else
    echo "FAILED: sentinel $sent"
    picture_guard
    exit 1
  fi
  for u in $units; do
    systemctl stop "$u" 2>/dev/null
  done
}

ok=0; fail=0; dry=0; n=0
while IFS= read -r line || [ -n "$line" ]; do
  case "$line" in ''|\#*) continue ;; esac
  id=$(printf '%s' "$line" | tr -d '\r' | awk '{$1=$1};1')
  [ -n "$id" ] || continue   # whitespace-only line
  case "$id" in *' '*|*';'*|*'&'*|*'|'*|*'`'*|*'$'*) echo "REFUSE (not a bare id): $id"; fail=$((fail+1)); continue ;; esac
  case "$id" in
    *[!A-Za-z0-9@._-]*) echo "REFUSE (not a bare id): $id"; fail=$((fail+1)); continue ;;
  esac
  denied=0
  for d in $DENY; do [ "$id" = "$d" ] && denied=1; done
  case "$id" in vetrotvapp*|unified-drm-*) denied=1 ;; esac
  if [ "$denied" = "1" ]; then echo "REFUSE (denylist): $id"; fail=$((fail+1)); continue; fi

  n=$((n+1))
  if [ "$APPLY" != "1" ]; then
    echo "DRY[$n] pkgcmd -D -t app -n '$id' --global"
    plant_sentinel "$id"
    dry=$((dry+1))
    continue
  fi
  { echo "echo undo: pkgcmd -A -t app -n '$id' --global"; echo "pkgcmd -A -t app -n '$id' --global"; } >> "$UNDO_LOG"
  pkgcmd -D -t app -n "$id" --global >/tmp/pkgcmd-apply.out 2>&1
  flag=$(read_flag "$id")
  if [ "$flag" = "true" ]; then
    echo "disabled[$n]: $id"
    ok=$((ok+1))
    plant_sentinel "$id"
  else
    echo "FAILED[$n]: $id flag=${flag:-missing} (undo line already recorded; stopping per discipline #2)"
    tail -2 /tmp/pkgcmd-apply.out
    picture_guard
    exit 1
  fi
done < "$LIST"

picture_guard

echo
if [ "$APPLY" = "1" ]; then
  echo "summary: disabled=$ok failed=$fail of $n (undo: cat $UNDO_LOG | sh)"
else
  echo "dry run: would disable $dry of $n entries (re-run with APPLY=1)"
fi
# A run that read nothing is a failure, not a success: an empty list, a list
# full of comments or a list whose every line was refused must not report
# "0 of 0" and exit 0 (review 2026-10-30).
if [ "$n" = "0" ]; then
  echo "FAIL: $LIST yielded no valid app ids"
  exit 2
fi
[ "$fail" = "0" ] || exit 1
